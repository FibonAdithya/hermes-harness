"""Build repo registry rows from scans, GitHub and the wiki index, and render the pages.

Pure functions: no I/O except the injected `readme` callable.
Privacy: a public row never takes its purpose or a page link from a private page, and a
public row's purpose or page link that names a private row's repo is dropped.
"""
import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass

from . import frontmatter
from .reposcan import HOSTS, Checkout, GhRepo, Overrides, PageRef, _cap

BANDS = ("hot", "active", "dormant", "lookup failed")
COLUMNS = ("laptop", "hermes-vm", "tig-adi")
NO_DESCRIPTION = "(no description)"
NOTE = ("<!-- Generated by hermes-wiki repos. Edits are lost; "
        "change ~/.config/hermes-wiki/repos.toml instead. -->")
FOOTER = "Private repos: [[repos-private]]"
_NAMES_HOSTS = frozenset(h.name for h in HOSTS if h.mode == "names")
_ACTIVITY_HOSTS = ("laptop", "tig-adi")  # local-only repo activity: laptop first


@dataclass
class Row:
    key: str
    slug: str | None
    purpose: str
    pages: list[str]
    band: str
    last_commit: str | None
    paths: dict[str, list[str]]
    private: bool


def band(commits_30d: int | None) -> str:
    if commits_30d is None:
        return "lookup failed"
    if commits_30d <= 0:
        return "dormant"
    if commits_30d < 20:
        return "active"
    return "hot"


def _name(key: str) -> str:
    """Repo name of a row key: the part after owner/, or after local:."""
    if key.startswith("local:"):
        return key[len("local:"):]
    return key.partition("/")[2]


def _word(name: str) -> re.Pattern:
    return re.compile(r"(?<!\w)" + re.escape(name) + r"(?!\w)", re.IGNORECASE)


def _bare(key: str) -> str:
    """Lower-cased repo name of `local:x`, `owner/name` or a bare name."""
    key = key.strip()
    if key.lower().startswith("local:"):
        key = key[len("local:"):]
    return key.rpartition("/")[2].lower()


def private_names(rows: list[Row], index: dict[str, list[PageRef]], ov: Overrides) -> frozenset[str]:
    """Every repo name that must not appear on the public page: listed private rows, every
    repo any private page names (listed or not), and every `private` override."""
    names = {_name(r.key).lower() for r in rows if r.private}
    names |= {_bare(k) for k, refs in index.items() if any(p.private for p in refs)}
    names |= {_bare(k) for k in ov.private}
    return frozenset(n for n in names if n)


def private_names_in(text: str, names: Iterable[str]) -> list[str]:
    return sorted({n.lower() for n in names if n and _word(n).search(text)})


@dataclass
class _Acc:
    key: str  # first spelling seen
    checkouts: list[Checkout]
    gh: GhRepo | None = None


def build_rows(checkouts: list[Checkout], owned: list[GhRepo], extra: dict[str, GhRepo | None],
               index: dict[str, list[PageRef]], ov: Overrides,
               readme: Callable[[str], str | None]) -> list[Row]:
    known: dict[str, GhRepo] = {}
    for repo in owned:
        known.setdefault(repo.slug.lower(), repo)
    for slug, repo in extra.items():
        if repo is not None:
            known.setdefault(slug.lower(), repo)
    include = {k.lower() for k in ov.include}
    exclude = {k.lower() for k in ov.exclude}
    clone_owners = {o.lower() for o in ov.clone_owners}

    # every non-mirror checkout, grouped by key (case-insensitive)
    groups: dict[str, _Acc] = {}
    mirrors: list[Checkout] = []
    for c in checkouts:
        if c.host in _NAMES_HOSTS:
            mirrors.append(c)
            continue
        key = c.slug if c.slug is not None else f"local:{c.local_name}"
        acc = groups.setdefault(key.lower(), _Acc(key, []))
        acc.checkouts.append(c)
    for acc in groups.values():  # scan order must not change the page
        acc.checkouts.sort(key=lambda c: (c.path, c.host))
        acc.key = acc.checkouts[0].slug or f"local:{acc.checkouts[0].local_name}"

    listed: dict[str, _Acc] = {}

    def add(lk: str, spelling: str) -> _Acc:
        acc = listed.get(lk)
        if acc is None:
            acc = groups.get(lk) or _Acc(spelling, [])
            listed[lk] = acc
        acc.gh = known.get(lk)
        return acc

    def blocked(lk: str) -> bool:  # include is applied after, and wins
        repo = known.get(lk)
        return (repo is not None and (repo.fork or repo.archived)) or lk in exclude

    for repo in owned:
        lk = repo.slug.lower()
        if not blocked(lk):
            add(lk, repo.slug)
    for lk, acc in groups.items():
        if lk.startswith("local:"):
            if not blocked(lk):
                add(lk, acc.key)
        elif lk.partition("/")[0] in clone_owners and not blocked(lk):
            add(lk, acc.key)  # unknown GhRepo (lookup failed) is listed (ruling R2)
    failed = {slug.lower(): slug for slug, repo in extra.items() if repo is None}
    for lk in include:
        if lk in known or lk in groups:
            add(lk, known[lk].slug if lk in known else groups[lk].key)
        elif lk in failed:
            add(lk, failed[lk])  # spec rule 4: an include is listed even when its lookup failed

    # hermes-vm mirrors attach by directory name to an owner's row; they never list a repo
    mirror_paths: dict[str, list[str]] = {}
    for c in sorted(mirrors, key=lambda c: c.path):
        for owner in ov.owners:
            lk = f"{owner}/{c.local_name}".lower()
            if lk in listed:
                mirror_paths.setdefault(lk, []).append(c.path)
                break

    private_keys = {k.lower() for k in ov.private}
    # a bare entry (no `local:`, no owner/) moves any row with that repo name
    private_bare = {k for k in private_keys if not k.startswith("local:") and "/" not in k}
    # the public-page check scrubs by bare name, so a row is private when its name is a private
    # name: `local:Notes` still hides FibonAdithya/Notes, and a private page
    # naming tig-foundation/valuebook hides FibonAdithya/valuebook
    hidden_pre = private_names([], index, ov)
    draft: list[tuple[str, _Acc, list[PageRef], bool]] = []
    for lk, acc in listed.items():
        refs = {p.name: p for p in index.get(_name(lk), [])}
        if not lk.startswith("local:"):
            refs.update({p.name: p for p in index.get(lk, [])})  # `repos: [owner/name]`
        refs = sorted(refs.values(), key=lambda p: (p.name.casefold(), p.name))
        private = (any(p.private for p in refs) or lk in private_keys or _name(lk) in private_bare
                   or _name(lk).lower() in hidden_pre)
        draft.append((lk, acc, refs, private))

    private_rows = [Row(acc.gh.slug if acc.gh else acc.key, None, "", [], "", None, {}, True)
                    for _, acc, _, private in draft if private]
    hidden = private_names(private_rows, index, ov)

    def leaks(text: str) -> bool:
        return bool(private_names_in(text, hidden))

    purposes = {k.lower(): v for k, v in ov.purpose.items()}
    rows: list[Row] = []
    for lk, acc, refs, private in draft:
        local = lk.startswith("local:")
        key = acc.gh.slug if acc.gh else acc.key
        if not private:
            refs = [p for p in refs if not p.private and not leaks(p.name)]
        name = _name(lk)
        page = next((p for p in refs if p.name.lower() == name), refs[0] if refs else None)

        def sources():
            yield purposes.get(lk)
            yield page.purpose if page else None
            yield acc.gh.description if acc.gh else None
            for c in acc.checkouts:
                if c.host == "laptop":
                    yield readme(c.path)

        purpose = NO_DESCRIPTION
        for text in sources():
            if text and text.strip():
                text = _cap(text.strip())
                if private or not leaks(text):
                    purpose = text
                    break

        if local:
            pick = None
            for host in _ACTIVITY_HOSTS:
                for c in acc.checkouts:
                    if c.host == host and (pick is None or (pick.commits_30d is None and c.commits_30d is not None)):
                        pick = c
            count = pick.commits_30d if pick else None
            last = pick.last_commit if pick else None
        elif acc.gh is not None:
            count, last = acc.gh.commits_30d, acc.gh.last_commit
        else:
            count, last = None, None

        paths: dict[str, list[str]] = {}
        for c in acc.checkouts:
            got = paths.setdefault(c.host, [])
            if c.path not in got:
                got.append(c.path)
        for p in mirror_paths.get(lk, []):
            got = paths.setdefault("hermes-vm", [])
            if p not in got:
                got.append(p)

        rows.append(Row(key, None if local else key, purpose, [p.name for p in refs], band(count), last,
                        paths, private))

    rows.sort(key=lambda r: (r.key.lower(), r.key))
    rows.sort(key=lambda r: r.last_commit or "", reverse=True)
    rows.sort(key=lambda r: (BANDS.index(r.band), r.last_commit is None))
    return rows


_BREAK = re.compile(r"\r\n|[\n\r\x0b\x0c\x1c\x1d\x1e\x85  ]")


def _cell(text: str) -> str:
    text = _BREAK.sub(" ", text)
    text = text.replace("\\", "\\\\").replace("|", "\\|").replace("<", "&lt;")
    text = re.sub(r"\[(?=\[)", "[ ", text)
    return re.sub(r"\](?=\])", "] ", text)


def _link(name: str) -> str:
    return f"[[{_cell(name)}]]"


def render(rows: list[Row], *, private: bool, today: str, host_notes: list[str]) -> str:
    meta = {"type": "log", "tags": ["coding", "finance"] if private else ["coding"], "updated": today}
    lines = [NOTE, ""]
    if host_notes:
        lines += [f"- {_cell(n)}" for n in host_notes] + [""]
    lines.append("| repo | purpose | activity | last commit | " + " | ".join(COLUMNS) + " |")
    lines.append("|" + "---|" * (4 + len(COLUMNS)))
    for r in rows:
        repo = _cell(r.slug) if r.slug else f"{_cell(_name(r.key))} (local only)"
        purpose = _cell(r.purpose)
        if r.pages:
            purpose += " (" + ", ".join(_link(p) for p in r.pages) + ")"
        cells = [repo, purpose, _cell(r.band), _cell(r.last_commit or "")]
        cells += ["<br>".join(_cell(p) for p in r.paths.get(h, [])) for h in COLUMNS]
        lines.append("| " + " | ".join(cells) + " |")
    if not private:
        lines += ["", FOOTER]
    return frontmatter.dump(meta, "\n".join(lines) + "\n")


def _drop_updated(text: str) -> list[str]:
    lines = text.split("\n")
    if lines and lines[0] == "---":
        for i in range(1, len(lines)):
            if lines[i] == "---":
                return [l for j, l in enumerate(lines) if not (0 < j < i and l.startswith("updated:"))]
    return lines


def same_page(a: str, b: str) -> bool:
    return _drop_updated(a) == _drop_updated(b)
